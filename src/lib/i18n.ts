export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'pt-BR';
  const lang = navigator.language.toLowerCase();
  if (lang.startsWith('pt')) return 'pt-BR';
  if (lang.startsWith('es')) return 'es';
  return 'en';
}
